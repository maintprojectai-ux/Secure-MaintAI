// Severity and Status types (strictly matching backend AlertSeverity: CRITICAL, HIGH, MEDIUM, LOW)
type SeverityType = "Critical" | "High" | "Medium" | "Low";
type StatusType = "Active" | "Resolved" | "Monitored";

